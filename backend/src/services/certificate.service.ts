export async function loadTemplate(key: string): Promise<Template> {
  const row = unwrapMaybe(
    await db.from("document_templates").select("template_key, title, sections, footer, version").eq("template_key", key).maybeSingle()
  ) as Template | null;
  if (!row) throw notFound(`Template ${key}`);
  return row;
}

export async function listTemplates(): Promise<Template[]> {
  return unwrapList(await db.from("document_templates").select("template_key, title, sections, footer, version, updated_at").order("template_key")) as Template[];
}

export async function updateTemplate(user: SessionUser, key: string, input: { title: string; sections: { heading: string; body: string }[]; footer: string }) {
  const current = await loadTemplate(key);
  // The template disclaimer cannot be edited away: a footer must still say it is a template.
  if (!/template/i.test(input.footer)) {
    throw new AppError(400, "FOOTER_REQUIRED", "The footer must keep saying this is a template to be verified with a legal practitioner.");
  }
  return unwrap(
    await db
      .from("document_templates")
      .update({ title: input.title, sections: input.sections, footer: input.footer, version: current.version + 1, updated_by: user.id })
      .eq("template_key", key)
      .select("template_key, title, sections, footer, version")
      .single()
  ) as Template;
}

const STAGE_CUSTODIAN: Record<string, string> = {
  SCENE: "Police (collecting officer)",
  FORENSIC_LAB: "Forensic laboratory",
  PROSECUTOR: "Prosecution",
  COURT: "Court",
};

export interface CertificateInput {
  custodianName?: string | null;
  custodianDesignation?: string | null;
  deviceDescription?: string | null;
  productionMethod?: string | null;
}

/** Fills every placeholder from the record, or throws listing exactly what is missing. */
export async function certificateFields(evidenceId: string, user: SessionUser, input: CertificateInput) {
  const item = unwrapMaybe(await db.from("evidence_items").select("*").eq("id", evidenceId).maybeSingle()) as any;
  if (!item) throw notFound("Evidence item");
  const anchor = item.anchor_id ? await loadAnchor(item.anchor_id) : null;
  const missing: string[] = [];

  if (!anchor || anchor.state !== "CONFIRMED" || item.chain_evidence_id === null) {
    missing.push("a confirmed anchor on the blockchain (the item's verification state must be CONFIRMED)");
  }

  // The hash in the certificate is the chain's, read now, never the database's alone.
  let anchoredDigest: string | null = null;
  if (item.chain_evidence_id !== null && chainReader().ready()) {
    try {
      anchoredDigest = (await chainReader().evidence(Number(item.chain_evidence_id))).fileHash;
    } catch {
      anchoredDigest = null;
    }
  }
  if (!anchoredDigest) missing.push("the anchored digest, read from the blockchain (it could not be read)");
  else if (anchoredDigest !== String(item.anchored_digest).toLowerCase()) {
    missing.push("agreement between the record and the blockchain (they differ; resolve the alert first)");
  }

  const manifest = item.capture_manifest as any;
  const deviceDescription =
    input.deviceDescription?.trim() ||
    (item.source === "capture" && manifest
      ? `NyaySetu ${manifest.platform} application ${manifest.appVersion}, device identifier ${manifest.deviceId}, ` +
        `capturing ${manifest.mediaKind.replace("_", "-")} through the device camera${manifest.mediaKind === "photo" ? "" : " and microphone"}.`
      : null);
  if (!deviceDescription) missing.push("a description of the device or source (not recorded for an uploaded file; enter it)");

  const productionMethod =
    input.productionMethod?.trim() ||
    (item.source === "capture"
      ? "Recorded live through the NyaySetu application. The SHA-256 of the exact bytes the camera produced was computed on the device before upload, " +
        "committed with the device time and position fix in a capture manifest, and the manifest's SHA-256 was anchored on the public ledger. " +
        "The file was encrypted with AES-256-GCM before storage."
      : null);
  if (!productionMethod) missing.push("how the record was produced (not recorded for an uploaded file; enter it)");

  const custodianName = input.custodianName?.trim() || user.fullName;
  const custodianDesignation = input.custodianDesignation?.trim() || user.designation;
  if (!custodianDesignation) missing.push("the custodian's designation");

  if (missing.length) {
    throw new AppError(422, "CERTIFICATE_INCOMPLETE", `The certificate cannot be generated yet. Missing: ${missing.join("; ")}.`, { missing });
  }

  const custody = unwrapList(await db.from("custody_events").select("id").eq("evidence_id", item.id)) as unknown[];

  const fields: Record<string, string> = {
    custodian_name: custodianName,
    custodian_designation: custodianDesignation!,
    device_description: deviceDescription!,
    production_method: productionMethod!,
    file_sha256: item.file_hash,
    anchored_digest: anchoredDigest!,
    public_ref: item.public_ref,
    tx_hash: anchor!.tx_hash ?? "",
    tx_explorer: anchor!.tx_hash ? explorerUrl(anchor!.tx_hash) ?? "" : "",
    captured_at: istDateTimeSeconds(item.device_time ?? item.collected_at),
    registered_at: istDateTimeSeconds(anchor!.confirmed_at ?? anchor!.submitted_at ?? item.created_at),
    custodian_role: STAGE_CUSTODIAN[item.current_stage] ?? item.current_stage,
    custody_count: String(custody.length),
    file_name: item.file_name,
    case_id: item.case_id,
  };
  return { item, fields };
}

export function fillPlaceholders(text: string, fields: Record<string, string>): string {
  return text.replace(/\{(\w+)\}/g, (match, key) => (key in fields ? fields[key] : match));
}

export async function renderCertificate(evidenceId: string, user: SessionUser, input: CertificateInput) {
  const { item, fields } = await certificateFields(evidenceId, user, input);
  const template = await loadTemplate(CERTIFICATE_KEY);

  const pdf = await buildTemplatePdf({
    title: template.title,
    reference: item.public_ref,
    sections: template.sections.map((s) => ({ heading: s.heading, body: fillPlaceholders(s.body, fields) })),
    footer: template.footer,
    signatures: [
      { role: "Person in charge of the device / record (Part A)", name: fields.custodian_name, designation: fields.custodian_designation },
      { role: "Expert (Part B)", name: null, designation: null },
    ],
  });

  const pdfSha = sha256Hex(pdf);
  await db.from("certificates").insert({
    evidence_id: item.id,
    case_id: item.case_id,
    template_key: template.template_key,
    template_version: template.version,
    pdf_sha256: pdfSha,
    anchored_digest: fields.anchored_digest,
    fields: { ...fields, case_id: undefined },
    generated_by: user.id,
    generated_role: user.role,
  });

  return { pdf, pdfSha, fields, item, templateVersion: template.version };
}
