/**
 * The Section 63 certificate (2.0 · F11).
 *
 * The Bharatiya Sakshya Adhiniyam, 2023 requires a certificate to accompany an
 * electronic record offered in evidence, in the form in its Schedule: Part A by
 * the party, Part B by an expert. This fills the template from the record —
 * device, how it was produced, the SHA-256, times, custodian, the anchor — and
 * refuses to render if a field it needs is missing, rather than leaving a blank
 * that looks filled.
 *
 * It is a TEMPLATE. Every page says so, the template text is editable by the
 * registry without code changes, and nothing here claims legal compliance.
 */

export const CERTIFICATE_KEY = "section63_certificate";

export interface Template {
  template_key: string;
  title: string;
  sections: { heading: string; body: string }[];
  footer: string;
  version: number;
}

