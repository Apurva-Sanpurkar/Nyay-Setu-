#!/usr/bin/env node
/**
 * Builds database/upgrade_2_0.sql: migrations 008–013 in order, in one file, so
 * an existing 1.0 database can be upgraded with a single paste into the Supabase
 * SQL Editor. Every migration is idempotent, so running the bundle twice is safe.
 *
 *   node scripts/bundle-upgrade.mjs          write the bundle
 *   node scripts/bundle-upgrade.mjs --check  fail if the bundle is out of date
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "database", "migrations");
const out = path.join(root, "database", "upgrade_2_0.sql");
const files = ["008_case_intake.sql", "009_verification_state.sql", "010_passport_capture.sql", "011_chunked_uploads.sql", "012_workflows.sql", "013_upload_staging.sql"];

const header = `-- ===========================================================================
-- NyaySetu :: upgrade_2_0.sql
--
-- Upgrades a database that already has migrations 001–007 to NyaySetu 2.0.
-- It is migrations 008 to 013, in order, in one file. Generated by
-- scripts/bundle-upgrade.mjs — edit the migrations, not this file.
--
-- HOW TO RUN
--   1. Supabase dashboard → Database → Backups: confirm a recent backup exists.
--   2. SQL Editor → New query → paste this whole file → Run.
--   3. Check: open <your API>/api/health and confirm
--      subsystems.database.schema.upToDate is true.
--
-- SAFETY
--   Additive only: creates tables, columns, functions, policies and triggers.
--   Nothing is dropped and no existing row is deleted. Idempotent: running it
--   twice changes nothing the second time.
-- ===========================================================================
`;

const body = files
  .map((f) => `\n\n-- ###########################################################################\n-- ${f}\n-- ###########################################################################\n\n${readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n").trimEnd()}\n`)
  .join("");
const bundle = header + body;

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== bundle) {
    console.error("database/upgrade_2_0.sql is out of date. Run: node scripts/bundle-upgrade.mjs");
    process.exit(1);
  }
  console.log("database/upgrade_2_0.sql matches migrations 008–013.");
} else {
  writeFileSync(out, bundle);
  console.log(`Wrote ${path.relative(root, out)} (${bundle.length.toLocaleString()} characters).`);
}
